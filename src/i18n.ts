let current: AppLocale = 'en';

export function isAppLocale(value: string): value is AppLocale {
  return (LOCALES as readonly string[]).includes(value);
}

export function detectLocale(): AppLocale {
  const nav = (navigator.language || 'en').toLowerCase();
  const full = nav.replace('_', '-');
  if (isAppLocale(full)) return full;
  /* Prefer regional tags when the browser reports them */
  if (full.startsWith('nl-be')) return 'nl-BE';
  if (full.startsWith('de-at')) return 'de-AT';
  if (full.startsWith('de-ch')) return 'de-CH';
  const short = full.slice(0, 2);
  if (isAppLocale(short)) return short;
  return 'en';
}

export function getLocale(): AppLocale {
  return current;
}

export function setLocale(locale: AppLocale): void {
  current = locale;
  document.documentElement.lang = LOCALE_BCP47[locale];
}

export function t(key: string): string {
  return TABLES[current][key] ?? TABLES.en[key] ?? key;
}

/** Apply `data-i18n` / `data-i18n-aria` / `data-i18n-label` under root. */
export function applyI18n(root: ParentNode = document): void {
  root.querySelectorAll<HTMLElement>('[data-i18n]').forEach((el) => {
    const key = el.getAttribute('data-i18n');
    if (!key) return;
    const text = t(key);
    if (el.hasAttribute('data-i18n-html')) el.innerHTML = text;
    else el.textContent = text;
  });
  root.querySelectorAll<HTMLElement>('[data-i18n-aria]').forEach((el) => {
    const key = el.getAttribute('data-i18n-aria');
    if (key) el.setAttribute('aria-label', t(key));
  });
  root.querySelectorAll<HTMLElement>('[data-i18n-label]').forEach((el) => {
    const key = el.getAttribute('data-i18n-label');
    if (key) el.setAttribute('label', t(key));
  });
}
